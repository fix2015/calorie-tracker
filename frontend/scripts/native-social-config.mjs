/* global process, console */
// Writes ios/social-login.generated.xcconfig from .env.capacitor so Info.plist gets the reversed
// Google iOS client id as a URL scheme (required by Google Sign-In). Runs as part of `build:cap`.
//   VITE_GOOGLE_IOS_CLIENT_ID=1234-abc.apps.googleusercontent.com → com.googleusercontent.apps.1234-abc
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env.capacitor');
const out = join(root, 'ios', 'social-login.generated.xcconfig');

const env = {};
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const clientId = process.env.VITE_GOOGLE_IOS_CLIENT_ID || env.VITE_GOOGLE_IOS_CLIENT_ID || '';
if (!clientId) {
  rmSync(out, { force: true });
  console.log('[native-social-config] VITE_GOOGLE_IOS_CLIENT_ID not set — Google URL scheme left as placeholder');
} else {
  const reversed = clientId.split('.').reverse().join('.');
  writeFileSync(out, `// Generated by scripts/native-social-config.mjs — do not edit or commit\nGOOGLE_REVERSED_CLIENT_ID = ${reversed}\n`);
  console.log(`[native-social-config] wrote ${out}`);
}
